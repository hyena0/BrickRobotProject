#!/usr/bin/env bash
# Start the local MQTT broker (Mosquitto) for the EV3 bricks with one command.
#
# Usage (from the repo root):
#   scripts/start_broker.sh              # auto-detect LAN IP, run in foreground
#   scripts/start_broker.sh --ip 192.168.0.10
#   scripts/start_broker.sh --check      # only print settings, do not start
#
# Policy: local only. No authentication, listeners on 127.0.0.1 and the hub's
# LAN IP only (never 0.0.0.0). No external brokers, no port forwarding.
set -euo pipefail

PORT=1883
IP=""
CHECK_ONLY=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --ip) IP="${2:-}"; shift 2 ;;
    --port) PORT="${2:-}"; shift 2 ;;
    --check) CHECK_ONLY=1; shift ;;
    -h|--help) sed -n '2,12p' "$0"; exit 0 ;;
    *) echo "Unknown option: $1" >&2; exit 2 ;;
  esac
done

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CONF="$REPO_ROOT/config/mosquitto.local.conf"
HW="$REPO_ROOT/config/hardware.local.yaml"

# 1) Mosquitto installed?
MOSQ="$(command -v mosquitto || true)"
for p in /opt/homebrew/sbin/mosquitto /usr/local/sbin/mosquitto; do
  [[ -z "$MOSQ" && -x "$p" ]] && MOSQ="$p"
done
if [[ -z "$MOSQ" ]]; then
  echo "mosquitto not found. Install: brew install mosquitto" >&2
  exit 1
fi

# 2) LAN IP (Wi-Fi en0 first, then en1, then any private IPv4)
if [[ -z "$IP" ]]; then
  for ifc in en0 en1; do
    IP="$(ipconfig getifaddr "$ifc" 2>/dev/null || true)"
    [[ -n "$IP" ]] && break
  done
fi
if [[ -z "$IP" ]]; then
  IP="$(ifconfig 2>/dev/null | awk '/inet (10|192\.168|172\.(1[6-9]|2[0-9]|3[01]))\./{print $2; exit}')"
fi
if [[ -z "$IP" ]]; then
  echo "Could not detect a LAN IP. Use --ip <address>." >&2
  exit 1
fi
case "$IP" in
  10.*|192.168.*|172.1[6-9].*|172.2[0-9].*|172.3[01].*) ;;
  *) echo "Refusing non-private IP: $IP (local-only policy)" >&2; exit 1 ;;
esac

# 3) Port free?
if lsof -nP -iTCP:"$PORT" -sTCP:LISTEN >/dev/null 2>&1; then
  echo "Port $PORT is already in use:" >&2
  lsof -nP -iTCP:"$PORT" -sTCP:LISTEN >&2
  echo "Stop it first (e.g. 'brew services stop mosquitto' or kill the PID)." >&2
  exit 1
fi

# 4) Write config (regenerated every run; git-ignored *.local.*)
mkdir -p "$(dirname "$CONF")"
cat > "$CONF" <<EOF
# Generated by scripts/start_broker.sh - do not edit by hand.
# Local only: no auth, bound to loopback and the hub LAN IP.
listener $PORT 127.0.0.1
listener $PORT $IP
allow_anonymous true
persistence false
log_dest stdout
log_type error
log_type warning
log_type notice
connection_messages true
EOF

# 5) Warn if the brick/PC config points to a different broker IP
if [[ -f "$HW" ]] && ! grep -q "$IP" "$HW"; then
  echo "WARNING: $HW does not contain $IP. Update the broker address there" >&2
  echo "         and hub_address in each brick's config/brick.local.json." >&2
fi

echo "Mosquitto : $MOSQ"
echo "Config    : $CONF"
echo "Listening : 127.0.0.1:$PORT, $IP:$PORT (anonymous, LAN only)"
[[ "$CHECK_ONLY" == 1 ]] && exit 0

echo "Starting broker. Press Ctrl+C to stop."
exec "$MOSQ" -c "$CONF"
